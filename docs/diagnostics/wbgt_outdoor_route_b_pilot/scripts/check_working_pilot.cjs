// CHG-0654: offline working-pilot browser contracts; run with node from the repository.
const path=require('path');
const {pathToFileURL}=require('url');
const repo=path.resolve(__dirname,'../../../..');
const {chromium}=require('playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1280,height:950}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(repo,'docs/diagnostics/wbgt_outdoor_route_b_pilot/working_pilot/index.html')).href);
 await page.waitForFunction(()=>window.pilotSelection);
 const payload=await page.locator('#pilot-data').textContent();const data=JSON.parse(payload);
 const eligible=data.units.find(u=>u.state==='Kerala'&&u.level==='district'&&u.eligible);
 await page.selectOption('#unit',String(eligible.id));
 let selection=await page.evaluate(()=>window.pilotSelection);
 const expected=eligible.series.historical.reduce((s,r)=>s+r[3],0)/21;
 if(Math.abs(selection.value-expected)>1e-10)throw Error('Historical display differs from source');
 await page.selectOption('#scenario','ssp585');await page.selectOption('#period','2060-2080');
 selection=await page.evaluate(()=>window.pilotSelection);
 if(selection.rows.length!==21||selection.rows[0][0]!==2060||selection.rows.at(-1)[0]!==2080)throw Error('Future period wrong');
 const expectedFuture=eligible.series.ssp585.slice(40).reduce((s,r)=>s+r[3],0)/21;
 if(Math.abs(selection.value-expectedFuture)>1e-10)throw Error('Future display differs from source');
 const downloadEvent=page.waitForEvent('download');await page.click('#download');const download=await downloadEvent;const csv=fs.readFileSync(await download.path(),'utf8');
 if(!csv.includes('grid_first_cell_metrics')||!csv.includes('2060'))throw Error('Download missing provenance/years');
 const excluded=data.units.find(u=>u.state==='Kerala'&&u.level==='district'&&!u.eligible);await page.selectOption('#unit',String(excluded.id));
 if(await page.locator('#selectedValue').textContent()!=='No data')throw Error('Missing unit rendered as value');
 if(!await page.locator('#missing').isVisible())throw Error('Missing coverage hidden');
 await page.selectOption('#level','block');await page.selectOption('#district','Palakkad');
 if(!(await page.locator('#unit option').count()))throw Error('Block drilldown empty');
 await page.selectOption('#metric','1');
 if(!(await page.locator('#definition').textContent()).includes('each cell'))throw Error('Maximum semantics unclear');
 await page.screenshot({path:path.join(repo,'scratch/wbgt_route_b/working_pilot_desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile horizontal overflow');
 await page.screenshot({path:path.join(repo,'scratch/wbgt_route_b/working_pilot_mobile.png'),fullPage:true});
 if(errors.length)throw Error(errors.join('\n'));
 console.log(JSON.stringify({status:'PASS',units:data.units.length,eligible:data.units.filter(u=>u.eligible).length,checks:['historical values','future period and values','CSV provenance','excluded units','block drilldown','maximum semantics','mobile layout','no browser errors']},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
